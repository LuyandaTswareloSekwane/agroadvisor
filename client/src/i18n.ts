const validationMessageKeys: Record<string, string> = {
  'Enter your email address.': 'validation.emailRequired',
  'Enter a valid email address, like name@example.com.': 'validation.emailInvalid',
  'Enter your password.': 'validation.passwordRequired',
  'Create a password.': 'validation.passwordCreate',
  'Enter your password again.': 'validation.passwordAgain',
  'Passwords do not match.': 'validation.passwordMismatch',
  'Enter your full name.': 'validation.fullName',
  'Enter a name for your farm.': 'validation.farmName',
  'Enter the nearest town or village.': 'validation.place',
  'Enter the size of your farm.': 'validation.farmSize',
  'Enter whole numbers of animals (0 if you do not keep that animal).': 'validation.animals',
  'Select or add at least one crop, or enter the animals you keep, so we can tailor your advice.':
    'validation.cropRequired',
};

export function translateValidationMessage(language: AppLanguage, message: string): string {
  const directKey = validationMessageKeys[message];
  if (directKey) return translate(language, directKey);

  const passwordLength = message.match(/^Use at least (\d+) characters\.$/);
  if (passwordLength) return translate(language, 'auth.passwordHint', { count: passwordLength[1] ?? '' });

  const maxLength = message.match(/^Use (\d+) characters or fewer\.$/);
  if (maxLength) return translate(language, 'validation.maxLength', { count: maxLength[1] ?? '' });

  const coordinateRequired = message.match(/^Choose your farm on the map or enter its (latitude|longitude)\.$/);
  if (coordinateRequired) {
    return translate(language, `validation.${coordinateRequired[1] ?? ''}Required`);
  }

  const coordinateRange = message.match(/^Enter a (latitude|longitude) between -(\d+) and \d+\.$/);
  if (coordinateRange) {
    return translate(language, `validation.${coordinateRange[1] ?? ''}Range`, { limit: coordinateRange[2] ?? '' });
  }

  const farmSizeRange = message.match(/^Enter a size between 0 and ([\d,]+) hectares\.$/);
  if (farmSizeRange) {
    return translate(language, 'validation.farmSizeRange', { limit: farmSizeRange[1] ?? '' });
  }

  const cropLimit = message.match(
    /^Add up to (\d+) crop names, with no name longer than (\d+) characters\.$/,
  );
  if (cropLimit) {
    return translate(language, 'validation.cropLimit', {
      count: cropLimit[1] ?? '',
      max: cropLimit[2] ?? '',
    });
  }

  return message;
}

